-- ════════════════════════════════════════════════════════════════════════════
--  «مدينة اللاذقية» عالقةٌ في المجمّع التربوي، ولا أحدَ أضافها.
--
--  المديرُ يفتح «إعدادات المدرسة» فيجد في قائمة «المجمّع التربوي» خياراً لم
--  يضعه، ولا يراه المشرفُ في «القوائم المرجعية» ليحذفه. فمن أين يأتي؟
--
--  ليس من lookup_lists: getLookupList تُصفّي بالمديرية تصفيةً سليمة. بل من
--  setSelectPreserving (school/script.js) — وهي تحقن **القيمة المحفوظة** خياراً
--  إن غابت عن القائمة. وذلك سلوكٌ مقصودٌ وصحيح: `select.value = x` حيث لا خيارَ
--  قيمتُه x يُرجع الحقلَ فارغاً بصمت، فيقرأ الحفظُ لاحقاً '' ويمحو ما كان
--  محفوظاً. فالحقنُ يحمي البيانات، لا يفسدها.
--
--  إذن القيمةُ في schools.complex_name، أثرٌ من عهدٍ كان الحقل فيه نصّاً حرّاً
--  قبل أن يصير قائمةً يضبطها المشرف. وتعليقُ الدالّة نفسه يسمّي هذه الحالة:
--  «أو مجمّعٍ لم يعرّفه المشرف بعد».
--
--  والمصيدةُ أنّ الحقل مطلوبٌ عند الحفظ — فلا يستطيع المديرُ اختيار «— اختر —»
--  ليتخلّص منها. القيمةُ العالقة هي الخيارُ الوحيد القابل للحفظ، فتُخلَّد.
--
--  التنظيفُ هنا **مبدئيٌّ لا موجَّهٌ لقيمةٍ بعينها**: يُفرَّغ كلُّ مجمّعٍ لا
--  تقابله منطقةٌ تعليميةٌ فعّالة في مديرية المدرسة. فيُزال «مدينة اللاذقية»
--  وكلُّ أثرٍ آخر من عهد النصّ الحرّ، ولا تُمسّ قيمةٌ عرّفها المشرفُ فعلاً.
--  وبعدها يختار المديرُ من القائمة الحقيقية.
-- ════════════════════════════════════════════════════════════════════════════

do $ruqi_orphan$
declare
  v_cleared integer;
begin
  update public.schools s
     set complex_name = null
   where s.complex_name is not null
     and not exists (
       select 1
       from public.lookup_lists l
       where l.list_type = 'educational_zone'
         and l.active
         and l.value = s.complex_name
         -- العامّة (directorate_id فارغ) صالحةٌ للجميع، والخاصّةُ لمديريتها.
         and (l.directorate_id is null or l.directorate_id = s.directorate_id)
     );

  get diagnostics v_cleared = row_count;
  raise notice 'مجمّعاتٌ يتيمةٌ فُرّغت: %', v_cleared;
end
$ruqi_orphan$;
