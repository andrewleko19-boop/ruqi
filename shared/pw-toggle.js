// ─────────────────────────────────────────────────────────────────────────────
//  زرّ إظهار/إخفاء كلمة المرور — مصدرٌ واحد للبوّابات التي تفتقر إليه.
//
//  بوّابتا المدرسة والمعلم تملكان الزرّ ضمن ترميزهما الخاص؛ أمّا الوزارة
//  والمديرية والمشرف فكانت حقولها عمياء تماماً. على الجوّال — وهو الجهاز الغالب
//  هنا — لوحةُ المفاتيح العربية/اللاتينية تتبدّل والحروف تُخطَأ بلا أن يُرى ذلك،
//  فيقرأ المستخدم «البريد أو كلمة المرور غير صحيحة» فيظنّ الخلل في النظام أو في
//  حسابه لا في حرفٍ واحد أخطأه. الزرّ يُنهي هذا الالتباس بنقرة.
//
//  لا خطر أمنيّ يُذكر: الإظهار مؤقّت وبإرادة المستخدم وحده، وهو سلوكٌ قياسيّ في
//  كلّ التطبيقات الكبرى.
// ─────────────────────────────────────────────────────────────────────────────

/** يربط زرّ `.pw-toggle` المجاور بحقل كلمة المرور المُمرَّر. */
export function setupPwToggle(input) {
  if (!input) return;
  const btn = input.parentElement?.querySelector('.pw-toggle');
  if (!btn) return;
  const use = btn.querySelector('use');

  btn.addEventListener('click', () => {
    const hidden = input.type === 'password';
    input.type = hidden ? 'text' : 'password';
    // setAttribute لا الخاصية: href في SVG ينتمي لفضاء أسماء XLink في بعض
    // المتصفّحات، وتعيينُه ككائن لا يُحدِّث الرمز المعروض.
    use?.setAttribute('href', hidden ? '#ic-eye-off' : '#ic-eye');
    btn.setAttribute('aria-label', hidden ? 'إخفاء كلمة المرور' : 'إظهار كلمة المرور');
  });
}
