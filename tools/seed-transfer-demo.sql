       'c1a55000-0000-4000-8000-00000000000b'::uuid,
       v.full_name, v.first_name, v.father_name, v.grandfather_name, v.family_name,
       v.mother_name, v.birth_date::date, v.gender, v.national_id, 'active'
from (values
