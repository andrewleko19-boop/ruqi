-- ── ١) المدرستان ─────────────────────────────────────────────────────────────
-- المجمع التربوي والمديرية يظهران في ترويسة «ورقة لا مانع» المطبوعة، فلا بدّ
-- من تعبئتهما وإلا خرجت الترويسة ناقصة.
insert into public.schools (id, name, directorate_id, complex_name, school_type)
select v.id, v.name,
       (select d.id from public.directorates d
         where d.name like '%اللاذقية%' order by d.name limit 1),
       'مدينة اللاذقية', 'primary'
from (values
  ('5e3d0000-0000-4000-8000-00000000700a'::uuid, 'طارق بن زياد ح1 صباحي'),
  ('5e3d0000-0000-4000-8000-00000000700b'::uuid, 'خالد بن الوليد ح1 صباحي')
) as v(id, name)
on conflict (id) do nothing;


-- ── ٢) الصفوف والشعب ─────────────────────────────────────────────────────────
-- «طارق» (المستقبِلة) تحتاج شعباً في الأول والرابع والخامس ليُجرَّب النوعان:
--   • العادية  → شعبة في **نفس** صفّ الطالب (الأول).
--   • الاستثنائية → شعبة في صفّ **مختلف** (الخامس).
-- ولغات أجنبية مختلفة لأن «اللغة» تُطبع على الورقة من شعبة الاستقبال.
-- والشعبة الرابعة في الصف الأول تحمل level_track = 1: شعبة «المستوى الأول» بعد
-- دمج المديرية للمستويات في الصفوف النظامية — تبقى داخل صفّها النظامي.
insert into public.classes (id, school_id, name, grade, section, academic_year,
                            foreign_language, level_track)
select v.id, v.school_id, v.name, v.grade, v.section, '2025-2026', v.lang, v.lvl
from (values
  -- طارق بن زياد (المستقبِلة)
  ('c1a55000-0000-4000-8000-000000000001'::uuid, '5e3d0000-0000-4000-8000-00000000700a'::uuid,
   'الأول - الأولى',   'الأول',  'الأولى',  'انكليزي', null::smallint),
  ('c1a55000-0000-4000-8000-000000000002'::uuid, '5e3d0000-0000-4000-8000-00000000700a'::uuid,
   'الأول - الرابعة',  'الأول',  'الرابعة', 'انكليزي', 1::smallint),
  ('c1a55000-0000-4000-8000-000000000003'::uuid, '5e3d0000-0000-4000-8000-00000000700a'::uuid,
   'الخامس - الثانية', 'الخامس', 'الثانية', 'فرنسي',   null::smallint),
  -- خالد بن الوليد (الحالية)
  ('c1a55000-0000-4000-8000-00000000000b'::uuid, '5e3d0000-0000-4000-8000-00000000700b'::uuid,
   'الأول - الأولى',   'الأول',  'الأولى',  'انكليزي', null::smallint)
) as v(id, school_id, name, grade, section, lang, lvl)
on conflict (id) do nothing;


-- ── ٣) طالبان في «خالد بن الوليد» ────────────────────────────────────────────
